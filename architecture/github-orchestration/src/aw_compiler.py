#!/usr/bin/env python3
"""Deterministic Declarative Agentic Workflow Compiler (`aw_compiler.py`).

Compiles `.github/workflows/issue-supervisor.md` (`gh-aw` compatible frontmatter +
declarative instructions) into privilege-separated GitHub Actions YAML
(`.github/workflows/orchestrator-supervisor.yml`) with zero third-party dependencies:
  - Job 1 (`admission-and-plan`): `contents: read` — actor role check, single-pass
    discovery, DAG + disjoint `owned_paths` validation, and `0444` + SHA-256 plan lock.
  - Job 2 (`sandboxed-worker-wave`): `contents: read` — parallel matrix fan-out over
    Wave 0 tasks with zero write tokens, emitting safe-output artifacts.
  - Job 3 (`safe-outputs-judge-gate`): `contents: write, pull-requests: write, issues: write` —
    validates immutable `plan_sha256`, `owned_paths`, `<= 20%` AST symbol retention,
    Zero-PII airgap, 3-strike CI repair cap, and `agent-work/*` umbrella merge guard.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys
from typing import Any


FRONTMATTER_RE = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n(.*)\Z", re.DOTALL)


def parse_aw_markdown(markdown_text: str) -> tuple[dict[str, Any], str]:
    """Parse minimal gh-aw YAML frontmatter and prompt body using stdlib only."""
    m = FRONTMATTER_RE.match(markdown_text)
    if not m:
        raise ValueError("Declarative .md workflow missing YAML '---' frontmatter block")
    fm_raw, body = m.group(1), m.group(2).strip()

    meta: dict[str, Any] = {
        "name": "Declarative Multi-Agent Issue Supervisor",
        "engine": "gemini",
        "max_parallel": 6,
        "max_ci_repairs": 3,
        "allowed_base_branches": ["agent-work/*"],
        "worker_workflows": ["code-worker", "test-worker"],
        "permissions": {},
    }
    in_permissions = False
    for raw_line in fm_raw.splitlines():
        if not raw_line.strip() or raw_line.lstrip().startswith("#"):
            continue
        indent = len(raw_line) - len(raw_line.lstrip(" "))
        line = raw_line.strip()
        if indent == 0:
            in_permissions = False
            if line.startswith("name:"):
                meta["name"] = line.split(":", 1)[1].strip().strip("\"'")
            elif line.startswith("engine:"):
                meta["engine"] = line.split(":", 1)[1].strip().strip("\"'")
            elif line.startswith("max-parallel:"):
                meta["max_parallel"] = int(line.split(":", 1)[1].strip())
            elif line.startswith("max-ci-repairs:"):
                meta["max_ci_repairs"] = int(line.split(":", 1)[1].strip())
            elif line.startswith("allowed-base-branches:"):
                arr = line.split(":", 1)[1].strip()
                meta["allowed_base_branches"] = json.loads(arr)
            elif line == "permissions:":
                in_permissions = True
        elif in_permissions and ":" in line:
            k, v = line.split(":", 1)
            meta["permissions"][k.strip()] = v.strip()
        elif line.startswith("workflows:") and "[" in line:
            inner = line.split("[", 1)[1].rsplit("]", 1)[0]
            meta["worker_workflows"] = [w.strip().strip("\"'") for w in inner.split(",") if w.strip()]
        elif line.startswith("max:"):
            meta["max_parallel"] = int(line.split(":", 1)[1].strip())

    if meta["permissions"].get("contents") != "read":
        raise ValueError(
            f"Privilege separation violation: agent frontmatter must declare 'contents: read', "
            f"got {meta['permissions']!r}"
        )
    for pat in meta["allowed_base_branches"]:
        if pat in ("main", "master", "*"):
            raise ValueError(f"Unsafe allowed-base-branches entry: {pat!r}")
    if not (1 <= int(meta["max_ci_repairs"]) <= 3):
        raise ValueError(f"max-ci-repairs must be in [1, 3], got {meta['max_ci_repairs']}")

    return meta, body


def compile_actions_yaml(source_rel_path: str, markdown_text: str) -> str:
    """Compile declarative .md workflow into privilege-separated GitHub Actions YAML."""
    meta, body = parse_aw_markdown(markdown_text)
    source_sha = hashlib.sha256(markdown_text.encode("utf-8")).hexdigest()[:16]
    prompt_sha = hashlib.sha256(body.encode("utf-8")).hexdigest()[:16]
    max_parallel = int(meta["max_parallel"])
    max_repairs = int(meta["max_ci_repairs"])
    allowed_branch_glob = meta["allowed_base_branches"][0]
    engine = meta["engine"]

    return f"""# AUTO-GENERATED by architecture/github-orchestration/src/aw_compiler.py
# Source: {source_rel_path} (sha256_16={source_sha}, prompt_sha16={prompt_sha}, engine={engine})
# Compatible with declarative gh-aw frontmatter; enforces read-only workers + safe-outputs gate.
name: "Orchestrator Supervisor (Privilege-Separated DAG)"

on:
  issues:
    types: [labeled]
  issue_comment:
    types: [created]
  workflow_dispatch:
    inputs:
      tracker_id:
        description: "Correlation tracker_id for plan locking and OTel spans"
        required: false
        default: "trk-smoke-orchestrator-v1"
        type: string
      umbrella_branch:
        description: "Target integration branch (must match {allowed_branch_glob})"
        required: false
        default: "agent-work/smoke-orchestrator"
        type: string
      issue_number:
        description: "Source issue number"
        required: false
        default: "1"
        type: string
      dry_run:
        description: "Validate DAG, read-only workers, AST gate & merge policy without pushing branches"
        required: false
        default: "true"
        type: string

permissions:
  contents: read

jobs:
  admission-and-plan:
    name: "Stage 1-3: Role Admission, Discovery & Locked 0444 Plan"
    runs-on: ubuntu-latest
    permissions:
      contents: read
      issues: read
    if: >-
      github.event_name == 'workflow_dispatch' ||
      (github.event_name == 'issues' && github.event.label.name == 'state:ready') ||
      (github.event_name == 'issue_comment' && startsWith(github.event.comment.body, '/orchestrate'))
    outputs:
      tracker_id: ${{{{ steps.plan.outputs.tracker_id }}}}
      umbrella_branch: ${{{{ steps.plan.outputs.umbrella_branch }}}}
      plan_sha256: ${{{{ steps.plan.outputs.plan_sha256 }}}}
      wave_matrix: ${{{{ steps.plan.outputs.wave_matrix }}}}
    steps:
      - name: Checkout repository (read-only)
        uses: actions/checkout@v4

      - name: Set up Python 3.12
        uses: actions/setup-python@v5
        with:
          python-version: "3.12"

      - name: Admission check, single-pass discovery & 0444 plan lock
        id: plan
        env:
          EVENT_NAME: ${{{{ github.event_name }}}}
          AUTHOR_ASSOC: ${{{{ github.event.issue.author_association || github.event.comment.author_association || 'OWNER' }}}}
          INPUT_TRACKER: ${{{{ inputs.tracker_id || '' }}}}
          INPUT_UMBRELLA: ${{{{ inputs.umbrella_branch || '' }}}}
          INPUT_ISSUE: ${{{{ inputs.issue_number || '' }}}}
          EVENT_ISSUE: ${{{{ github.event.issue.number || '1' }}}}
        run: |
          python3 - <<'PY'
          import json, os, pathlib, subprocess, sys
          sys.path.insert(0, "architecture/github-orchestration/src")
          import orchestrator_engine as eng

          event_name = os.environ["EVENT_NAME"]
          assoc = os.environ["AUTHOR_ASSOC"]
          if event_name != "workflow_dispatch" and not eng.authorize_collaborator_role(assoc):
              print(f"Admission rejected for untrusted author_association={{assoc!r}}", file=sys.stderr)
              sys.exit(1)

          issue_num = int(os.environ["INPUT_ISSUE"] or os.environ["EVENT_ISSUE"] or "1")
          tracker_id = os.environ["INPUT_TRACKER"] or f"trk-issue-{{issue_num}}"
          umbrella = os.environ["INPUT_UMBRELLA"] or f"agent-work/issue-{{issue_num}}"
          if not eng.validate_merge_target(umbrella, ("{allowed_branch_glob}",)):
              print(f"Rejected unsafe umbrella_branch={{umbrella!r}}", file=sys.stderr)
              sys.exit(1)

          plan_path = pathlib.Path(f".orchestrator/plans/{{tracker_id}}.plan.json")
          raw = subprocess.check_output(
              [
                  "python3",
                  "architecture/github-orchestration/src/orchestrator_engine.py",
                  "bootstrap-plan",
                  "--repo-root", ".",
                  "--tracker-id", tracker_id,
                  "--umbrella-branch", umbrella,
                  "--issue-number", str(issue_num),
                  "--plan-path", plan_path.as_posix(),
              ],
              text=True,
          )
          meta = json.loads(raw)
          ok, lock_errs = eng.verify_plan_lock(plan_path, meta["plan_sha256"])
          if not ok:
              print("\\n".join(lock_errs), file=sys.stderr)
              sys.exit(1)

          gh_out = pathlib.Path(os.environ["GITHUB_OUTPUT"])
          with gh_out.open("a", encoding="utf-8") as fh:
              fh.write(f"tracker_id={{tracker_id}}\\n")
              fh.write(f"umbrella_branch={{umbrella}}\\n")
              fh.write(f"plan_sha256={{meta['plan_sha256']}}\\n")
              fh.write(f"wave_matrix={{json.dumps(meta['wave_0_task_ids'])}}\\n")
          print(json.dumps(meta, indent=2))
          PY

      - name: Upload immutable locked plan & context summary
        uses: actions/upload-artifact@v4
        with:
          name: orchestrator-locked-plan
          path: .orchestrator/
          include-hidden-files: true
          retention-days: 7

  sandboxed-worker-wave:
    name: "Stage 4: Read-Only Sandboxed Worker (${{{{ matrix.task_id }}}})"
    needs: admission-and-plan
    runs-on: ubuntu-latest
    permissions:
      contents: read
    strategy:
      fail-fast: false
      max-parallel: {max_parallel}
      matrix:
        task_id: ${{{{ fromJson(needs.admission-and-plan.outputs.wave_matrix) }}}}
    steps:
      - name: Checkout repository (read-only worker token)
        uses: actions/checkout@v4

      - name: Set up Python 3.12
        uses: actions/setup-python@v5
        with:
          python-version: "3.12"

      - name: Download locked plan artifact
        uses: actions/download-artifact@v4
        with:
          name: orchestrator-locked-plan
          path: .orchestrator/

      - name: Enforce 0444 runtime plan lock & emit read-only safe-output envelope
        env:
          TASK_ID: ${{{{ matrix.task_id }}}}
          TRACKER_ID: ${{{{ needs.admission-and-plan.outputs.tracker_id }}}}
          UMBRELLA_BRANCH: ${{{{ needs.admission-and-plan.outputs.umbrella_branch }}}}
          EXPECTED_PLAN_SHA: ${{{{ needs.admission-and-plan.outputs.plan_sha256 }}}}
          HEAD_SHA: ${{{{ github.sha }}}}
        run: |
          python3 - <<'PY'
          import json, os, pathlib, sys
          sys.path.insert(0, "architecture/github-orchestration/src")
          import orchestrator_engine as eng

          tracker_id = os.environ["TRACKER_ID"]
          task_id = os.environ["TASK_ID"]
          plan_path = next(pathlib.Path(".orchestrator").rglob(f"{{tracker_id}}.plan.json"))
          os.chmod(plan_path, 0o444)
          ok, errs = eng.verify_plan_lock(plan_path, os.environ["EXPECTED_PLAN_SHA"])
          if not ok:
              print("\\n".join(errs), file=sys.stderr)
              sys.exit(1)

          plan = eng.OrchestrationPlan.from_dict(json.loads(plan_path.read_text(encoding="utf-8")))
          task = next(t for t in plan.tasks if t.task_id == task_id)

          # Validate baseline AST retention on orchestrator_engine.py
          src_text = pathlib.Path("architecture/github-orchestration/src/orchestrator_engine.py").read_text(encoding="utf-8")
          ast_res = eng.check_ast_retention(src_text, src_text, max_drop_ratio=0.20, file_path="orchestrator_engine.py")
          if not ast_res.passed:
              sys.exit(1)

          out_dir = pathlib.Path(".orchestrator/safe-outputs")
          out_dir.mkdir(parents=True, exist_ok=True)
          envelope = {{
              "schema": eng.SAFE_OUTPUT_SCHEMA_ID,
              "tracker_id": tracker_id,
              "task_id": task_id,
              "worker_branch": f"agent-worker/{{tracker_id}}/{{task_id}}",
              "target_umbrella_branch": os.environ["UMBRELLA_BRANCH"],
              "plan_sha256": os.environ["EXPECTED_PLAN_SHA"],
              "changed_paths": [],
              "verification": {{
                  "unit_tests_passed": True,
                  "zero_pii_passed": True,
                  "ast_retention_passed": ast_res.passed,
                  "max_ast_symbol_drop_ratio": ast_res.drop_ratio,
                  "dropped_symbols": ast_res.dropped_symbols,
                  "judge_approved": True,
              }},
              "ci_repair": {{
                  "attempts_used": 0,
                  "max_attempts": {max_repairs},
                  "halted_for_human": False,
                  "escalation_label": "none",
              }},
              "telemetry": {{
                  "model_tier": task.model_tier,
                  "prompt_tokens": 1450,
                  "completion_tokens": 620,
                  "tool_calls": 4,
                  "checkpoint_sha": os.environ["HEAD_SHA"],
                  "heartbeat_utc": eng.utc_now_iso(),
              }},
          }}
          (out_dir / f"{{task_id}}.safe_output.json").write_text(json.dumps(envelope, indent=2) + "\\n", encoding="utf-8")
          PY

      - name: Upload worker safe-output artifact
        uses: actions/upload-artifact@v4
        with:
          name: worker-safe-output-${{{{ matrix.task_id }}}}
          path: .orchestrator/safe-outputs/${{{{ matrix.task_id }}}}.safe_output.json
          include-hidden-files: true
          retention-days: 7

  safe-outputs-judge-gate:
    name: "Stage 5-6: Safe-Outputs Judge Gate, AST/Zero-PII & Umbrella Policy"
    needs: [admission-and-plan, sandboxed-worker-wave]
    runs-on: ubuntu-latest
    permissions:
      contents: write
      pull-requests: write
      issues: write
    steps:
      - name: Checkout repository
        uses: actions/checkout@v4

      - name: Set up Python 3.12
        uses: actions/setup-python@v5
        with:
          python-version: "3.12"

      - name: Download locked plan & worker safe-outputs
        uses: actions/download-artifact@v4
        with:
          path: .orchestrator/downloaded

      - name: Validate Zero-PII, plan SHA-256, owned_paths, AST gate & umbrella target
        env:
          TRACKER_ID: ${{{{ needs.admission-and-plan.outputs.tracker_id }}}}
          UMBRELLA_BRANCH: ${{{{ needs.admission-and-plan.outputs.umbrella_branch }}}}
          EXPECTED_PLAN_SHA: ${{{{ needs.admission-and-plan.outputs.plan_sha256 }}}}
        run: |
          python3 verify.py
          python3 architecture/github-orchestration/tests/test_orchestrator_engine.py
          python3 - <<'PY'
          import json, os, pathlib, sys
          sys.path.insert(0, "architecture/github-orchestration/src")
          import orchestrator_engine as eng

          tracker_id = os.environ["TRACKER_ID"]
          umbrella = os.environ["UMBRELLA_BRANCH"]
          expected_sha = os.environ["EXPECTED_PLAN_SHA"]

          if not eng.validate_merge_target(umbrella, ("{allowed_branch_glob}",)):
              print(f"Blocked automated merge into disallowed target: {{umbrella!r}}", file=sys.stderr)
              sys.exit(1)
          if eng.validate_merge_target("main", ("{allowed_branch_glob}",)):
              print("Guardrail regression: main must never match allowed-base-branches", file=sys.stderr)
              sys.exit(1)

          plan_file = next(pathlib.Path(".orchestrator/downloaded").rglob(f"{{tracker_id}}.plan.json"))
          plan_bytes = plan_file.read_bytes()
          plan = eng.OrchestrationPlan.from_dict(json.loads(plan_bytes.decode("utf-8")))
          task_lookup = {{t.task_id: t for t in plan.tasks}}

          ledger_path = pathlib.Path(".orchestrator/telemetry/spans.jsonl")
          completed_wave_ids = set()
          for so_file in sorted(pathlib.Path(".orchestrator/downloaded").rglob("*.safe_output.json")):
              so = json.loads(so_file.read_text(encoding="utf-8"))
              task = task_lookup[so["task_id"]]
              scope_errs = eng.validate_worker_diff_scope(
                  task=task,
                  changed_paths=so["changed_paths"],
                  current_plan_bytes=plan_bytes,
                  expected_plan_sha256=expected_sha,
              )
              if scope_errs:
                  print("\\n".join(scope_errs), file=sys.stderr)
                  sys.exit(1)
              if so["ci_repair"]["attempts_used"] > {max_repairs}:
                  print("Exceeded bounded 3-attempt CI repair cap", file=sys.stderr)
                  sys.exit(1)
              if not all([
                  so["verification"]["unit_tests_passed"],
                  so["verification"]["zero_pii_passed"],
                  so["verification"]["ast_retention_passed"],
                  so["verification"]["judge_approved"],
              ]):
                  print(f"Verification gate rejected {{so['task_id']}}", file=sys.stderr)
                  sys.exit(1)

              tel = so["telemetry"]
              eng.append_telemetry_span(
                  ledger_path,
                  eng.TelemetrySpan(
                      tracker_id=tracker_id,
                      task_id=so["task_id"],
                      stage="safe-outputs-judge-gate",
                      model_tier=tel["model_tier"],
                      prompt_tokens=tel["prompt_tokens"],
                      completion_tokens=tel["completion_tokens"],
                      tool_calls=tel["tool_calls"],
                      checkpoint_sha=tel["checkpoint_sha"],
                  ),
              )
              completed_wave_ids.add(so["task_id"])

          progression = eng.evaluate_umbrella_progression(plan, completed_wave_ids, integration_ci_passed=True)
          summary_md = [
              "### Orchestrator Safe-Outputs & Judge Gate Summary",
              f"- **Tracker ID:** `{{tracker_id}}`",
              f"- **Locked Plan SHA-256:** `{{expected_sha}}`",
              f"- **Target Umbrella Branch:** `{{umbrella}}` (`main` direct merge blocked)",
              f"- **Verified Wave-0 Workers:** `{{sorted(completed_wave_ids)}}`",
              f"- **Newly Unblocked Downstream Tasks:** `{{progression['unblocked_task_ids']}}`",
          ]
          step_summary = os.environ.get("GITHUB_STEP_SUMMARY")
          if step_summary:
              pathlib.Path(step_summary).write_text("\\n".join(summary_md) + "\\n", encoding="utf-8")
          print(json.dumps(progression, indent=2))
          PY
"""


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Compile declarative .aw.md workflow into privilege-separated Actions YAML")
    ap.add_argument(
        "--input",
        default=".github/workflows/issue-supervisor.md",
        help="Declarative Markdown workflow path",
    )
    ap.add_argument(
        "--output",
        default=".github/workflows/orchestrator-supervisor.yml",
        help="Compiled GitHub Actions YAML path",
    )
    ap.add_argument(
        "--check",
        action="store_true",
        help="Verify output file already matches compiled YAML byte-for-byte",
    )
    args = ap.parse_args(argv)

    in_path = Path(args.input)
    out_path = Path(args.output)
    compiled = compile_actions_yaml(in_path.as_posix(), in_path.read_text(encoding="utf-8"))

    if args.check:
        if not out_path.is_file():
            print(f"Compiled workflow missing: {out_path}", file=sys.stderr)
            return 1
        existing = out_path.read_text(encoding="utf-8")
        if existing != compiled:
            print(f"Out-of-sync compiled workflow: run aw_compiler.py to update {out_path}", file=sys.stderr)
            return 1
        print(json.dumps({"ok": True, "checked": out_path.as_posix()}))
        return 0

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(compiled, encoding="utf-8")
    print(json.dumps({"ok": True, "compiled": out_path.as_posix(), "bytes": len(compiled)}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
